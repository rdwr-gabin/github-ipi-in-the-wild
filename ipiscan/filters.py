"""Deterministic filters applied before any model sees the text.

1. Noise filter: drops hidden regions that are well-known machine markers left by
   GitHub apps (review bots, dependency bots, preview deployers) and items written by
   known bot accounts. These markers are hidden by design and are never agent-directed
   instructions.
2. Authorship: a coarse class (owner, trusted_tool, bot, human_contributor, unknown)
   that the classifiers receive as trusted context.
"""
from __future__ import annotations

import re

from .items import Item

NOISE_BOT_AUTHORS = frozenset({
    "coderabbitai[bot]", "dependabot[bot]", "renovate[bot]", "netlify[bot]",
    "github-actions[bot]", "cursor[bot]", "devin-ai-integration[bot]",
    "greptile-apps[bot]", "sourcery-ai[bot]", "codacy-production[bot]",
    "qodo-code-review[bot]", "socket-security[bot]", "sonarqubecloud[bot]",
    "cubic-dev-ai[bot]", "openshift-ci[bot]", "webcompat-bot", "k8s-ci-robot",
    "macroscopeapp[bot]", "ti-chi-bot[bot]", "openshift-trt[bot]", "runtipi-update-bot[bot]",
})

NOISE_EXACT = frozenset({
    "raw HTML omitted", "rebase-check", "tips_start", "tips_end",
    "suggestion_start", "suggestion_end", "walkthrough_start", "walkthrough_end",
    "internal state start", "internal state end",
    "finishing_touch_checkbox_start", "finishing_touch_checkbox_end",
    "usage_tips_start", "usage_tips_end",
    "pre_merge_checks_walkthrough_start", "pre_merge_checks_walkthrough_end",
    "devin-review-badge-begin", "devin-review-badge-end",
    "DESCRIPTION START", "DESCRIPTION END", "test report",
    "__TEST_RESULT__", "/__TEST_RESULT__",
    "START COPILOT CODING AGENT SUFFIX", "START COPILOT CODING AGENT TIPS",
    "ELLIPSIS_HIDDEN", "overview-comment", "dependency-review-pr-comment-marker",
})

NOISE_PREFIXES = (
    "This is an auto-generated comment", "This is an auto-generated reply",
    "end of auto-generated comment", "fingerprinting:", "renovate-debug:",
    "GitOpsUserAgent=", '{"checkboxId":', "DwQgtGAEAqAWCWBn",
    "gh-aw-agentic-workflow:", "gh-aw-workflow-id:", "gh-aw-expires:", "gh-aw-workflow-call",
    "META={", "LOCATIONS START", "LOCATIONS END", "Macroscope",
)
_PREVIEW_RE = re.compile(r"^\[.*Preview\]\(https?://")


def is_noise_region(text: str) -> bool:
    t = (text or "").strip()
    return (len(t) < 4 or t in NOISE_EXACT or t.startswith(NOISE_PREFIXES) or bool(_PREVIEW_RE.match(t)))


def apply_noise_filter(item: Item) -> Item | None:
    """Return the item with noise regions removed, or None when nothing is left."""
    if item.author in NOISE_BOT_AUTHORS or (item.surface != "readme" and item.author.endswith("[bot]")):
        return None
    item.regions = [r for r in item.regions if not is_noise_region(r.get("hidden_text", ""))]
    return item if item.regions else None


# -- authorship -------------------------------------------------------------------
# Specific, well-known GitHub apps whose output is legitimate tooling. A generic
# "something[bot]" is NOT trusted: anyone can register an app with such a name.
TRUSTED_TOOLS = {
    "dependabot", "dependabot-preview", "github-actions", "renovate", "renovate-bot",
    "socket-security", "codecov", "codecov-commenter", "sonarcloud", "sonarqubecloud",
    "snyk-bot", "mergify", "netlify", "vercel", "greenkeeper", "allcontributors",
    "imgbot", "pre-commit-ci", "gitguardian", "semantic-release-bot", "release-please",
    "github-advanced-security",
    "coderabbitai", "cubic-dev-ai", "copilot", "copilot-pull-request-reviewer",
    "chatgpt-codex-connector", "gemini-cli", "gemini-code-assist", "sweep-ai",
    "deepsource-autofix", "qodo-merge-pro", "pr-agent", "ellipsis-dev", "graphite-app",
    "korbit-ai", "codeant-ai", "bytebot", "devloai", "cursor", "sourcery-ai",
}
_TRUSTED_PATTERNS = [re.compile(r".*-approval-bot$", re.I), re.compile(r".*-ci(-bot)?$", re.I), re.compile(r"^prow.*", re.I)]
# AI tools that post through a person's login: recognised by content, not by account.
_TOOL_SIGNATURES = [
    re.compile(r"cubic:(attribution|review-post)|authored by cubic|cubic\.dev", re.I),
    re.compile(r"auto-generated comment by coderabbit|coderabbit\.ai", re.I),
    re.compile(r"generated by greptile|greptile\.com", re.I),
    re.compile(r"reviewed with ellipsis|ellipsis\.dev", re.I),
]


def _is_trusted_tool(login: str, text: str) -> bool:
    base = re.sub(r"\[bot\]$", "", login or "").strip().lower()
    return (base in TRUSTED_TOOLS or any(p.match(base) for p in _TRUSTED_PATTERNS)
            or any(s.search(text or "") for s in _TOOL_SIGNATURES))


def authorship(item: Item, text: str = "") -> str:
    """owner | trusted_tool | bot | human_contributor | unknown"""
    if _is_trusted_tool(item.author, text):
        return "trusted_tool"
    if item.author_is_bot or item.author.endswith("[bot]"):
        return "bot"
    owner = item.repo.split("/", 1)[0].lower() if "/" in item.repo else ""
    if not (owner and item.author):
        return "unknown"
    return "owner" if item.author.lower() == owner else "human_contributor"
